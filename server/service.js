// Runs the server so it survives closing the terminal or editor: a systemd user service (aisquad.service)
// on Linux, a launchd agent on macOS, else a detached process. The unit is generated from the plugin's
// current path and node binary, so after a plugin update the next /aisquad rewrites it and restarts.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync, spawn } from 'node:child_process';
import { config, ROOT } from './config.js';

export const UNIT = 'aisquad.service';
export const LAUNCHD_LABEL = 'net.sopwer.aisquad';
// settings that point the server somewhere else (scratch homes, private tmux, fake Claude) travel into the unit
const PASS_ENV = ['AISQUAD_HOME', 'CLAUDE_HOME', 'AISQUAD_TMUX_SOCKET', 'CLAUDE_BIN', 'AISQUAD_NO_SYSTEMD', 'AISQUAD_NO_HOOKS'];

export const unitPath = (env = process.env) => path.join(env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'systemd', 'user', UNIT);
export const plistPath = () => path.join(os.homedir(), 'Library', 'LaunchAgents', `${LAUNCHD_LABEL}.plist`);
export const logPath = () => path.resolve(config.home, 'server.log');

// what the service runs: node + server/index.js with the port and host, PATH so tmux, git and claude are found
export function serverCommand({ port = 8097, host = '127.0.0.1', node = process.execPath, root = ROOT, env = process.env } = {}) {
  const vars = { PATH: [path.dirname(node), env.PATH || '/usr/local/bin:/usr/bin:/bin'].join(':') };
  for (const k of PASS_ENV) if (env[k]) vars[k] = /HOME|BIN/.test(k) ? path.resolve(env[k]) : env[k];
  return { args: [node, path.join(root, 'server', 'index.js'), '--port', String(port), '--host', host], cwd: root, vars };
}

const sdQuote = (s) => (/^[\w./:@%+=,-]+$/.test(s) ? s : `"${String(s).replace(/(["\\])/g, '\\$1')}"`);
export function renderUnit(cmd, log = logPath()) {
  return `# Generated by The AI Squad (/aisquad). Rewritten when the plugin moves or updates.
[Unit]
Description=The AI Squad server
After=network.target

[Service]
Type=simple
WorkingDirectory=${cmd.cwd}
ExecStart=${cmd.args.map(sdQuote).join(' ')}
${Object.entries(cmd.vars).map(([k, v]) => `Environment=${sdQuote(`${k}=${v}`)}`).join('\n')}
Restart=always
RestartSec=3
# stop only the server: agents in tmux keep running
KillMode=process
StandardOutput=append:${log}
StandardError=append:${log}

[Install]
WantedBy=default.target
`;
}

const xml = (s) => String(s).replace(/[<>&"']/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&apos;' }[c]));
export function renderPlist(cmd, log = logPath()) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${LAUNCHD_LABEL}</string>
  <key>ProgramArguments</key>
  <array>${cmd.args.map((a) => `<string>${xml(a)}</string>`).join('')}</array>
  <key>WorkingDirectory</key><string>${xml(cmd.cwd)}</string>
  <key>EnvironmentVariables</key>
  <dict>${Object.entries(cmd.vars).map(([k, v]) => `<key>${xml(k)}</key><string>${xml(v)}</string>`).join('')}</dict>
  <key>KeepAlive</key><true/>
  <key>RunAtLoad</key><true/>
  <key>StandardOutPath</key><string>${xml(log)}</string>
  <key>StandardErrorPath</key><string>${xml(log)}</string>
</dict>
</plist>
`;
}

// run(file, args) -> stdout (throws on failure); injectable for tests
const realRun = (file, args) => execFileSync(file, args, { encoding: 'utf8', timeout: 15000, stdio: ['ignore', 'pipe', 'pipe'] });

export function detectMode({ run = realRun, platform = process.platform, env = process.env } = {}) {
  if (env.AISQUAD_SERVICE === 'detached') return 'detached';
  if (platform === 'darwin') return 'launchd';
  if (platform !== 'linux') return 'detached';
  try { run('systemctl', ['--user', 'show-environment']); return 'systemd'; } catch { return 'detached'; }
}

function writeIfChanged(file, text) {
  let cur = null; try { cur = fs.readFileSync(file, 'utf8'); } catch { /* new */ }
  if (cur === text) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return true;
}

// start (or refresh) the service. Returns { mode, changed, started }
export function start(opts = {}, { run = realRun, mode = detectMode({ run }), spawnDetached = defaultSpawn } = {}) {
  const cmd = serverCommand(opts);
  fs.mkdirSync(config.home, { recursive: true });
  if (mode === 'systemd') {
    const changed = writeIfChanged(opts.unitFile || unitPath(), renderUnit(cmd));
    if (changed) run('systemctl', ['--user', 'daemon-reload']);
    run('systemctl', ['--user', 'enable', UNIT]);
    run('systemctl', ['--user', changed || opts.force ? 'restart' : 'start', UNIT]);
    return { mode, changed: changed || !!opts.force, started: true };
  }
  if (mode === 'launchd') {
    const file = opts.plistFile || plistPath();
    const changed = writeIfChanged(file, renderPlist(cmd));
    if (changed || opts.force) { try { run('launchctl', ['unload', file]); } catch { /* not loaded */ } }
    try { run('launchctl', ['load', '-w', file]); } catch { /* already loaded */ }
    return { mode, changed: changed || !!opts.force, started: true };
  }
  spawnDetached(cmd);
  return { mode, changed: false, started: true };
}

function defaultSpawn(cmd) {
  const out = fs.openSync(logPath(), 'a');
  const child = spawn(cmd.args[0], cmd.args.slice(1), { cwd: cmd.cwd, detached: true, stdio: ['ignore', out, out], env: { ...process.env, ...cmd.vars } });
  child.unref();
}

// stop the service; a detached server is stopped through its pid file
export function stop({ run = realRun, mode = detectMode({ run }), plistFile = plistPath() } = {}) {
  if (mode === 'systemd' && installed({ mode })) { try { run('systemctl', ['--user', 'stop', UNIT]); return { mode, stopped: true }; } catch { /* fall through */ } }
  if (mode === 'launchd' && fs.existsSync(plistFile)) { try { run('launchctl', ['unload', plistFile]); return { mode, stopped: true }; } catch { /* fall through */ } }
  const pidFile = path.join(config.home, 'server.pid');
  const pid = Number((() => { try { return fs.readFileSync(pidFile, 'utf8'); } catch { return 0; } })());
  if (!pid) return { mode: 'detached', stopped: false };
  try { process.kill(pid, 'SIGTERM'); return { mode: 'detached', stopped: true }; } catch { return { mode: 'detached', stopped: false }; }
}

export function installed({ mode = detectMode(), unitFile = unitPath(), plistFile = plistPath() } = {}) {
  return mode === 'systemd' ? fs.existsSync(unitFile) : mode === 'launchd' ? fs.existsSync(plistFile) : false;
}

// { mode, installed, active, enabled, linger } for /aisquad status
export function status({ run = realRun, mode = detectMode({ run }), unitFile = unitPath(), plistFile = plistPath() } = {}) {
  const ask = (file, args) => { try { return run(file, args).trim(); } catch (e) { return String(e.stdout || '').trim() || 'unknown'; } };
  const out = { mode, installed: installed({ mode, unitFile, plistFile }) };
  if (mode === 'systemd' && out.installed) {
    out.active = ask('systemctl', ['--user', 'is-active', UNIT]);
    out.enabled = ask('systemctl', ['--user', 'is-enabled', UNIT]);
    out.linger = ask('loginctl', ['show-user', os.userInfo().username, '-p', 'Linger', '--value']);
  }
  if (mode === 'launchd' && out.installed) out.active = ask('launchctl', ['list', LAUNCHD_LABEL]) !== 'unknown' ? 'active' : 'inactive';
  return out;
}

// remove the service (the server stops; ~/.aisquad and the Floors stay)
export function uninstall({ run = realRun, mode = detectMode({ run }), unitFile = unitPath(), plistFile = plistPath() } = {}) {
  if (mode === 'systemd' && fs.existsSync(unitFile)) {
    try { run('systemctl', ['--user', 'disable', '--now', UNIT]); } catch { /* already gone */ }
    fs.rmSync(unitFile);
    try { run('systemctl', ['--user', 'daemon-reload']); } catch { /* fine */ }
    return { mode, removed: true };
  }
  if (mode === 'launchd' && fs.existsSync(plistFile)) {
    try { run('launchctl', ['unload', '-w', plistFile]); } catch { /* not loaded */ }
    fs.rmSync(plistFile);
    return { mode, removed: true };
  }
  return { mode, removed: false, ...stop({ run, mode: 'detached' }) };
}
