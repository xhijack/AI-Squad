// Template + override inheritance (SPEC "Override rules") and the generated .claude/agents/<id>.md.
import { stringifyFrontmatter } from './frontmatter.js';
import { MODELS, EFFORTS, cleanPermissions, cleanAppearance } from './roles.js';
import { uniq, bad } from './util.js';

export const GENERATED_MARK = '<!-- GENERATED by The AI Squad';

const strs = (v) => (Array.isArray(v) ? v : []).map((x) => String(x).trim()).filter(Boolean);

export function cleanOverrides(o = {}) {
  const out = {};
  if (MODELS.includes(o.model)) out.model = o.model;
  if (EFFORTS.includes(o.effort)) out.effort = o.effort;
  const add = strs(o.skills?.add), remove = strs(o.skills?.remove);
  if (add.length || remove.length) out.skills = { add: uniq(add), remove: uniq(remove) };
  const rules = strs(o.rules);
  if (rules.length) out.rules = rules;
  if (o.permissions && (o.permissions.deny?.length || o.permissions.allow)) out.permissions = cleanPermissions(o.permissions);
  if (o.prompt && String(o.prompt).trim()) out.prompt = String(o.prompt).trim();
  return out;
}

// Overrides may only make permissions stricter: extra deny rules are fine, allow rules must be
// a subset of what the template already allows.
export function permissionViolations(tpl, over) {
  if (!over || !over.allow) return [];
  const allowed = new Set(tpl.allow || []);
  return over.allow.filter((a) => !allowed.has(a)).map((a) => `allow "${a}" is not allowed by the template`);
}

export function mergePermissions(tpl, over) {
  const bad_ = permissionViolations(tpl, over);
  if (bad_.length) throw bad(`Overrides may only be stricter than the template: ${bad_.join('; ')}`);
  const out = { deny: uniq([...(tpl.deny || []), ...(over?.deny || [])]) };
  if (over?.allow) out.allow = over.allow.filter((a) => (tpl.allow || []).includes(a));
  else if (tpl.allow) out.allow = [...tpl.allow];
  return out;
}

// agent: { id, displayName, role: { template, version, detached }, overrides, appearance, definition? }
// template: parsed Role Template of the locked version (or agent.definition when detached)
export function effectiveAgent(template, agent) {
  const o = cleanOverrides(agent.overrides || {});
  const remove = new Set(o.skills?.remove || []);
  return {
    id: agent.id,
    displayName: agent.displayName,
    role: template.role,
    title: template.title,
    version: template.version,
    detached: !!agent.role?.detached,
    lead: !!agent.lead,
    description: template.description,
    model: o.model || template.model,
    effort: o.effort || template.effort,
    skills: uniq([...template.skills.filter((s) => !remove.has(s)), ...(o.skills?.add || [])]),
    tools: [...template.tools],
    permissions: mergePermissions(template.permissions, o.permissions),
    rules: [...template.rules, ...(o.rules || [])],
    prompt: [template.prompt, o.prompt].filter(Boolean).join('\n\n'),
    appearance: { ...cleanAppearance(template.appearance), ...cleanAppearance(agent.appearance || {}) },
  };
}

function gitRules(git) {
  if (!git) return [];
  const out = [];
  const strategy = { 'agent-branches': 'Work on your own branch `<your-id>/<topic>`; never commit to the main branch directly.',
    'feature-branches': 'Work on a feature branch `feature/<topic>`; never commit to the main branch directly.',
    trunk: 'Commit small, tested changes directly to the main branch.' }[git.branchStrategy];
  if (strategy) out.push(strategy);
  out.push('Use Conventional Commits (`feat(scope): ...`, `fix(scope): ...`).');
  if (git.commitIdentity === 'per-agent') out.push('Your commits carry your own name and email (set for your session); do not change `git config user.*`.');
  if (git.noAiAttribution !== false) out.push('No AI attribution in commits or PRs: no Co-Authored-By trailers, no "Generated with" lines.');
  if (git.pushPolicy !== 'agents-may-push') out.push('Never run `git push`. Merges and pushes are done by The AI Squad server after the quality gate passes.');
  if (git.qualityGate) out.push(`Quality gate: \`${git.qualityGate}\` must pass before you report work as done.`);
  if (git.branchStrategy !== 'trunk') out.push(`Commit finished work on your branch and leave \`${git.mainBranch || 'main'}\` alone: the server ${git.mergeMethod === 'merge' ? 'merges' : 'squash-merges'} it ${git.mergePolicy === 'manual' ? 'when the owner says so' : 'once the quality gate passes'}.`);
  return out;
}

// several repositories (Phase 3.4): this repository is the primary one (the Floor, the board); the linked ones are
// open to the agent with --add-dir, and read-only ones are also denied every write at start time
export function repoRules(repos, lead = false) {
  const out = ['This repository is the primary one: the board, the docs and the handoffs live here.'];
  for (const r of repos) {
    out.push(r.access === 'write'
      ? `\`${r.path}\` (${r.id}, ${r.abs}): you may edit and commit there on your sprint branch (${r.branch.strategy === 'trunk' ? `directly on \`${r.branch.main}\`` : `not on \`${r.branch.main}\``}). Never push.${r.gate ? ` Its quality gate: \`${r.gate}\`.` : ''}`
      : `\`${r.path}\` (${r.id}, ${r.abs}): read only, for context. Never change files there and never run git writes in it; a change it needs goes into the module handoff for its maintainer.`);
  }
  if (lead) out.push('In docs/squad PLAN and TASKS, name the repository of every module (a module may span two). Gates, QA and merges run per repository touched.');
  return out;
}

// Standard Claude Code agent file. Permissions are enforced at start time (--disallowedTools);
// they are also listed here so the agent knows its limits.
// standard: the Floor's Blueprint ({ title, version, text, roleRules, lead }), written into every agent prompt
// skillName(name): the name the skill is known by in Claude Code (aisquad:<name> for our plugin's copy)
// repos: this agent's linked repositories ({ id, path, abs, access, branch, gate }); lead: it plans the board
// the servers the owner registered (Floor settings → Servers): reachable with ssh; everything else is local
export const serverRules = (servers) => [
  ...servers.map((s) => `\`${s.host}\`${s.purpose ? `: ${s.purpose}` : ''} (reach it with \`ssh ${s.host} <command>\`; allowed, also in background runs)`),
  'Only these are servers. Everything else is this machine (local development): do not mix the two up, and do not guess other hosts. Production changes, sudo and installs still wait for the owner.',
];
export function renderAgentFile(eff, { floorName = '', git = null, workflow = 'free-team', standard = null, skillName = (n) => n, memory = null, autopilot = null, repos = [], lead = false, context = [], servers = [] } = {}) {
  const fm = {
    name: eff.id,
    description: `${eff.displayName} (${eff.title}) on ${floorName || 'this Floor'}. ${eff.description || ''}`.trim(),
    model: eff.model,
    effort: eff.effort,
  };
  if (eff.tools.length) fm.tools = eff.tools.join(', ');
  // agent files only understand whole tool names here: a rule like Bash(git push*) would remove Bash entirely.
  // Pattern rules are enforced with --disallowedTools when The AI Squad starts the agent.
  const wholeTools = eff.permissions.deny.filter((d) => /^\w+$/.test(d));
  if (wholeTools.length) fm.disallowedTools = wholeTools.join(', ');
  const usable = eff.skills.map(skillName).filter(Boolean);
  if (usable.length) fm.skills = usable.join(', ');
  const source = eff.detached ? 'a detached copy' : `${eff.role}@${eff.version} + overrides`;
  const sections = [
    `${GENERATED_MARK} from ${source}. Edit the Floor in The AI Squad (or .claude/aisquad/team.json), not this file. -->`,
    `# ${eff.displayName}`,
    `You are **${eff.displayName}**, the ${eff.title} of ${floorName ? `the "${floorName}" Floor` : 'this Floor'}. Your agent id is \`${eff.id}\`.`
      + ` Read \`AISQUAD.md\` first: it holds the project brief, goal and team.`
      + ' Before you start a module, read `docs/squad/LEARNINGS.md` (the project\'s patterns and pitfalls) if it exists.'
      + (workflow === 'squad-sprint' ? ' This Floor runs the Squad Sprint workflow: take work from the sprint board and hand finished work to QA.' : ''),
  ];
  if (standard) {
    const lead = standard.lead && standard.lead.id !== eff.id ? `Your lead is **${standard.lead.displayName}** (\`${standard.lead.id}\`): talk to the owner only through the lead and the questions file.` : 'You are the lead: you are the only agent who talks to the owner.';
    sections.push(`## Squad standard: ${standard.title} v${standard.version}\nThis squad follows the ${standard.title} Blueprint. ${lead}\n\n${standard.text}${standard.roleRules ? `\n\n### Your rules in this squad\n${standard.roleRules}` : ''}`);
  }
  if (context.length) sections.push(`## Context\n${context.map((r) => `- ${r}`).join('\n')}`);
  if (eff.rules.length) sections.push(`## Rules\n${eff.rules.map((r) => `- ${r}`).join('\n')}`);
  if (memory?.length) sections.push(`## Memory\n${memory.map((r) => `- ${r}`).join('\n')}`);
  if (memory?.length) sections.push('## Learnings\n- After each Retro (`docs/squad/retro/`), add 1-3 short entries to `docs/squad/LEARNINGS.md`: `- YYYY-MM-DD · retro sprint N: the pattern or pitfall, and what to do`. Keep entries short; remove ones that no longer hold.');
  if (autopilot?.length) sections.push(`## Autopilot\n${autopilot.map((r) => (r.startsWith('  ') ? r : `- ${r}`)).join('\n')}`);
  const g = gitRules(git);
  if (g.length) sections.push(`## Git\n${g.map((r) => `- ${r}`).join('\n')}`);
  if (repos.length) sections.push(`## Repositories\n${repoRules(repos, lead).map((r) => `- ${r}`).join('\n')}`);
  if (servers.length) sections.push(`## Servers\n${serverRules(servers).map((r) => `- ${r}`).join('\n')}`);
  if (usable.length) sections.push(`## Skills\nUse these skills through the Skill tool when relevant: ${usable.map((s) => `\`${s}\``).join(', ')}.`);
  if (eff.permissions.deny.length) sections.push(`## Not allowed\n${eff.permissions.deny.map((d) => `- \`${d}\``).join('\n')}`);
  if (eff.prompt) sections.push(`## Prompt\n${eff.prompt}`);
  return stringifyFrontmatter(fm, '\n' + sections.join('\n\n') + '\n');
}
