import { test } from 'node:test';
import assert from 'node:assert/strict';
import { effectiveAgent, renderAgentFile, cleanOverrides, mergePermissions } from '../server/compose.js';
import { parseFrontmatter } from '../server/frontmatter.js';

const tpl = {
  role: 'frappe-developer', title: 'Frappe Developer', version: 3, description: 'Builds Frappe apps.', model: 'sonnet', effort: 'medium',
  skills: ['frappe', 'erpnext'], tools: ['Read', 'Edit'], permissions: { deny: ['Read(./.env)'], allow: ['Bash(bench *)', 'Bash(git *)'] },
  appearance: { style: 'spiky', shirt: '#3d82d6' }, rules: ['Never edit core.'], prompt: 'You are a Frappe developer.',
};
const agent = (overrides = {}, appearance = {}) => ({ id: 'ramdani-frappe-developer', displayName: 'Ramdani - Frappe Developer', role: { template: 'frappe-developer', version: 3 }, overrides, appearance });

test('no overrides = template', () => {
  const e = effectiveAgent(tpl, agent());
  assert.equal(e.model, 'sonnet');
  assert.deepEqual(e.skills, ['frappe', 'erpnext']);
  assert.deepEqual(e.rules, ['Never edit core.']);
  assert.equal(e.prompt, 'You are a Frappe developer.');
});

test('model, effort and appearance replace', () => {
  const e = effectiveAgent(tpl, agent({ model: 'opus', effort: 'high' }, { shirt: '#ff0000' }));
  assert.equal(e.model, 'opus');
  assert.equal(e.effort, 'high');
  assert.deepEqual(e.appearance, { style: 'spiky', shirt: '#ff0000' });
});

test('skills add and remove relative to the template', () => {
  const e = effectiveAgent(tpl, agent({ skills: { add: ['playwright'], remove: ['erpnext'] } }));
  assert.deepEqual(e.skills, ['frappe', 'playwright']);
});

test('rules append and prompt is appended below the template prompt', () => {
  const e = effectiveAgent(tpl, agent({ rules: ['Use the sopwer app.'], prompt: 'Focus on HR.' }));
  assert.deepEqual(e.rules, ['Never edit core.', 'Use the sopwer app.']);
  assert.equal(e.prompt, 'You are a Frappe developer.\n\nFocus on HR.');
});

test('permissions may only be stricter', () => {
  assert.deepEqual(mergePermissions(tpl.permissions, { deny: ['Bash(rm *)'] }), { deny: ['Read(./.env)', 'Bash(rm *)'], allow: ['Bash(bench *)', 'Bash(git *)'] });
  assert.deepEqual(mergePermissions(tpl.permissions, { deny: [], allow: ['Bash(bench *)'] }).allow, ['Bash(bench *)']);
  assert.throws(() => effectiveAgent(tpl, agent({ permissions: { deny: [], allow: ['Bash(curl *)'] } })), /stricter/);
  assert.throws(() => mergePermissions({ deny: [] }, { deny: [], allow: ['Read'] }), /stricter/);
});

test('cleanOverrides drops empty and invalid fields', () => {
  assert.deepEqual(cleanOverrides({ model: 'gpt', effort: '', skills: { add: [], remove: [] }, rules: ['', ' '], prompt: '  ' }), {});
});

test('generated agent file is a valid Claude Code agent definition', () => {
  const e = effectiveAgent(tpl, agent({ rules: ['Extra rule.'] }));
  const text = renderAgentFile(e, { floorName: 'Sopwer HR', git: { branchStrategy: 'agent-branches', noAiAttribution: true, pushPolicy: 'never', qualityGate: 'bench run-tests' } });
  const { data, body } = parseFrontmatter(text);
  assert.equal(data.name, 'ramdani-frappe-developer');
  assert.equal(data.model, 'sonnet');
  assert.equal(data.tools, 'Read, Edit');
  assert.equal(data.disallowedTools, undefined, 'pattern rules are not put in the agent file (they would remove the whole tool)');
  assert.match(body, /## Not allowed\n- `Read\(\.\/\.env\)`/);
  assert.match(body, /GENERATED by The AI Squad from frappe-developer@3/);
  assert.match(body, /- Extra rule\./);
  assert.match(body, /No AI attribution/);
  assert.match(body, /Never run `git push`/);
  assert.match(body, /bench run-tests/);
  assert.match(body, /AISQUAD\.md/);
});

test('only whole tool names go into the agent file disallowedTools', () => {
  const e = effectiveAgent({ ...tpl, permissions: { deny: ['WebFetch', 'Bash(git push*)'] } }, agent());
  assert.equal(parseFrontmatter(renderAgentFile(e)).data.disallowedTools, 'WebFetch');
});
